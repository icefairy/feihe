    /**
     * 取某个键的提示文字。返回空串表示该键在本方案下没有可提示的内容
     * （自然码的 a/i/o/u/v），调用方应该隐藏提示、保持键面干净。
     *
     * @param letter 小写字母
     * @param mode 形码方案："ziranma" / "xiaohe" / 其它（返回空）
     */
    fun hintFor(letter: Char, mode: String): String {
        val key = letter.lowercaseChar()
        return when (mode) {
            "ziranma" -> ZIRANMA[key] ?: ""
            "xiaohe" -> XIAOHE[key] ?: ""
            else -> ""
        }
    }

    /**
     * 该键的**完整**形码列表（长按气泡用）。键面只放得下两个，其余靠长按查。
     *
     * 自然码返回 214 部首里的确定性对应；小鹤音形没有封闭映射表，返回
     * 键面上那两个高频字根（和 [hintFor] 相同）——它本来就没有可穷举的全集。
     */
    fun fullHint(letter: Char, mode: String): String {
        val key = letter.lowercaseChar()
        return when (mode) {
            "ziranma" -> ZIRANMA_FULL[key] ?: ""
            "xiaohe" -> XIAOHE[key] ?: ""
            else -> ""
        }
    }

    /** 该方案是否有任何键位提示（`off` 时整块功能都不该出现）。 */
    fun hasHints(mode: String): Boolean = mode == "ziranma" || mode == "xiaohe"

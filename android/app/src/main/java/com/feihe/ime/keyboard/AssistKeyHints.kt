/**
 * 形码（辅助码）模式的键位提示：26 个字母键各自对应哪些部首/部件。
 *
 * ## 用途
 *
 * 点「形」进入形码模式后，按键上原来的字母和标点暂时隐藏，改成小字显示
 * 「这个键能筛出什么部首」。用户照着键面按，不用背表——形码最大的门槛就是
 * 「我知道要打部首，但不知道哪个字母对应哪个部首」。
 *
 * ## 两套方案的数据来源
 *
 * - **自然码辅助码（本项目的「简版」）**：core/src/assist.rs 说得很清楚——
 *   取的是 **Unihan 康熙部首的读音首字母**（tools/gen_assist.py 的
 *   `RAD_INITIAL`，214 个部首按序号映射），**不是**官方自然码那套 26 键
 *   部件表（官方 `日/月/目`→`o`、`扌`→`f`、`山/石/十/食`→`u`）。用户
 *   2026-11-14 特意叮嘱「我们的自然码好像是修改的，记得按照实际的来」：
 *   键面就得照这套**实际编码规则**（部首读音首字母，1 键）来，不能抄官方表。
 *   所以 a/i/o/u/v 五键没有任何部首（RAD_INITIAL 里就没有这些首字母），
 *   21 个键合计 214 个部首，逐一键字数见 `AssistKeyHintsTest` 的闸门。
 * - **小鹤音形**：官网「鹤形：字根 → 部件字根」表（26 键，每键一组偏旁
 *   部首，日常称谓定键）。键面取官方表里字体安全的两个代表，长按气泡给
 *   该键完整部件表。见 [XIAOHE] / [XIAOHE_FULL] 的来源说明。
 *
 * ## 为什么每键只显示两个字
 *
 * 键宽只有屏宽的 1/10（约 36dp），46dp 高的键里还要放字母位置。三个字开始
 * 就挤成一团看不清，反而比没有提示更碍事。所以每键固定取两个（自然码取
 * 高频、小鹤取官方代表）。少数键官方只有一个部件（a 鱼、m 木、r 亻、t 田），
 * 就只显示一个，不硬凑。

package com.feihe.ime.keyboard

/**
 * 形码（辅助码）模式的键位提示：26 个字母键各自对应哪些部首/部件。
 *
 * ## 用途
 *
 * 点「形」进入形码模式后，按键上原来的字母和标点暂时隐藏，改成小字显示
 * 「这个键能筛出什么部首」。用户照着键面按，不用背表——形码最大的门槛就是
 * 「我知道要打部首，但不知道哪个字母对应哪个部首」。
 *
 * ## 两套方案的数据来源
 *
 * - **自然码辅助码**：规则是「部首读音首字母」（的→白→`b`、想→心→`x`）。
 *   所以键位映射可以从康熙 214 部首的读音首字母直接推出来，是**确定**的。
 * - **小鹤音形**：官方有 160 多个专用字根（带上、寿上、具上、既左…），
 *   26 键装不下，也不存在「一个键 = 固定几个部首」的封闭映射。这里给的是
 *   **按词库实际使用频次排出来的最高频字根**，作为提示而非权威表。
 *
 * ## 为什么每键只显示两个字
 *
 * 键宽只有屏宽的 1/10（约 36dp），46dp 高的键里还要放字母位置。三个字开始就
 * 挤成一团看不清，反而比没有提示更碍事。所以每键固定取**频次最高的两个**。
 */
